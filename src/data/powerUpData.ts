export function getTodayDailyChallenge(): DailyChallenge {
  const day = new Date().getDay(); // 0 is Sunday, 1 is Monday...
  const challenge = DAILY_CHALLENGES.find((c) => c.dayIndex === day);
  return challenge || DAILY_CHALLENGES[1];
}

export function isCosmeticUnlocked(
  item: CosmeticOption,
  player: PlayerProfile,
  unlockedList?: string[]
): boolean {
  if (item.unlockedByDefault) return true;
  if (unlockedList && unlockedList.includes(item.id)) return true;
  if (player.unlockedCosmeticIds && player.unlockedCosmeticIds.includes(item.id)) return true;
  if (item.requiredTier && player.mandarinMastery && player.mandarinMastery.tier >= item.requiredTier) {
    return true;
  }
  return false;
}

export function isPowerUpUnlocked(
  powerUp: MandarinPowerUp,
  player: PlayerProfile
): boolean {
  if (player.unlockedPowerUpIds?.includes(powerUp.id)) return true;
  const mastery = player.mandarinMastery;
  if (!mastery) return false;

  if (powerUp.category === 'tier') {
    return mastery.tier >= powerUp.masteryThreshold;
  }
  if (powerUp.category === 'streak') {
    return player.highestStreak >= powerUp.masteryThreshold;
  }
  // Category question threshold
  return mastery.correctAnswers >= powerUp.masteryThreshold;
}
